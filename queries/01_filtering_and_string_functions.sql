SET search_path TO public;


-- ---------------------------------------------------------------------
-- 1.1. Какие города есть в справочнике (без повторов)?
-- Техники: SELECT DISTINCT
-- ---------------------------------------------------------------------
SELECT DISTINCT city
FROM city;


-- ---------------------------------------------------------------------
-- 1.2. Города, название которых начинается на «L», заканчивается на «a»
--      и состоит из одного слова (без пробелов).
-- Техники: LIKE / NOT LIKE с шаблонами
-- ---------------------------------------------------------------------
SELECT city
FROM city
WHERE city LIKE 'L%a'
  AND city NOT LIKE '% %';


-- ---------------------------------------------------------------------
-- 1.3. Платежи дороже 1.00 за период с 17 по 19 июня 2005 года
--      включительно, в хронологическом порядке.
-- Техники: фильтр по диапазону дат через полуинтервал (>= ... < следующего дня),
--          ORDER BY
-- ---------------------------------------------------------------------
SELECT payment_id, amount, payment_date
FROM payment
WHERE payment_date >= '2005-06-17'
  AND payment_date < '2005-06-20'
  AND amount > 1
ORDER BY payment_date;


-- ---------------------------------------------------------------------
-- 1.4. Десять самых последних платежей (все поля).
-- Техники: ORDER BY ... DESC с дополнительным ключом сортировки, LIMIT
-- ---------------------------------------------------------------------
SELECT *
FROM payment
ORDER BY payment_date DESC, payment_id DESC
LIMIT 10;


-- ---------------------------------------------------------------------
-- 1.5. Карточка покупателя: «Фамилия Имя» одной строкой, email, длина email
--      и дата последнего обновления записи (без времени); алиасы на русском.
-- Техники: CONCAT_WS, LENGTH, CAST(... AS date), алиасы столбцов
-- ---------------------------------------------------------------------
SELECT
    CONCAT_WS(' ', last_name, first_name) AS "Фамилия и имя",
    email                                 AS "Электронная почта",
    LENGTH(email)                         AS "Длина поля email",
    CAST(last_update AS date)             AS "Дата последнего обновления"
FROM customer;


-- ---------------------------------------------------------------------
-- 1.6. Активные покупатели с именем KELLY или WILLIE; имя и фамилия
--      в нижнем регистре.
-- Техники: IN, LOWER
-- ---------------------------------------------------------------------
SELECT LOWER(first_name), LOWER(last_name), active
FROM customer
WHERE first_name IN ('KELLY', 'WILLIE')
  AND active = 1;


-- ---------------------------------------------------------------------
-- 1.7. Фильмы с рейтингом R и ценой аренды от 0 до 3 включительно,
--      а также фильмы PG-13 с ценой аренды от 4 и выше.
-- Техники: BETWEEN, комбинация условий AND / OR со скобками
-- ---------------------------------------------------------------------
SELECT title, rating, rental_rate
FROM film
WHERE (rating = 'R' AND rental_rate BETWEEN 0 AND 3)
   OR (rating = 'PG-13' AND rental_rate >= 4);


-- ---------------------------------------------------------------------
-- 1.8. Три фильма с самым длинным описанием и длина этого описания.
-- Техники: LENGTH, ORDER BY по выражению, FETCH FIRST n ROWS ONLY
-- ---------------------------------------------------------------------
SELECT title, description, LENGTH(description)
FROM film
WHERE description IS NOT NULL
ORDER BY LENGTH(description) DESC
FETCH FIRST 3 ROWS ONLY;


-- ---------------------------------------------------------------------
-- 1.9. Разбить email покупателя на имя почтового ящика (до @) и домен (после @).
-- Техники: SPLIT_PART
-- ---------------------------------------------------------------------
SELECT
    email,
    SPLIT_PART(email, '@', 1),
    SPLIT_PART(email, '@', 2)
FROM customer;


-- ---------------------------------------------------------------------
-- 1.10. То же, но имя ящика и домен с заглавной буквы, остальные буквы строчные.
-- Техники: подзапрос в FROM, UPPER / LOWER, LEFT, SUBSTRING, конкатенация ||
-- ---------------------------------------------------------------------
SELECT
    email,
    UPPER(LEFT(name_, 1)) || SUBSTRING(LOWER(name_), 2),
    UPPER(LEFT(domain_, 1)) || LOWER(SUBSTRING(domain_, 2))
FROM (
    SELECT
        email,
        SPLIT_PART(email, '@', 1) AS name_,
        SPLIT_PART(email, '@', 2) AS domain_
    FROM customer
) temp_tab;
